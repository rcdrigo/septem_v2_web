import assert from 'node:assert/strict';
import { build } from '../../node_modules/esbuild/lib/main.js';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
const dir = await mkdtemp(join(tmpdir(), 'native-editor-contracts-'));
try {
  await build({ entryPoints: ['src/lib/native-form-editor.ts'], bundle: true, platform: 'node', format: 'esm', outfile: join(dir, 'editor.mjs') });
  const { createNativeTable, moveNativeElement, convertNativeGroup, createNativeElement, createNativeGroup, createNativeTab, changeNativeElementType, editNativeElement, NATIVE_CATALOG } = await import(pathToFileURL(join(dir, 'editor.mjs')));
  assert.equal(NATIVE_CATALOG.length, 15);
  assert.equal(createNativeTab('Nova').groups.length, 1);
  assert.equal(createNativeGroup('table', 'Tabela').type, 'table');
  assert.equal(createNativeElement('textfield').key, '', 'campo novo começa sem chave');
  const list = { ...createNativeElement('select'), label: 'Valor', config: { values: [{ value: '1', label: 'Um' }], validate: { required: true }, description: 'Ajuda', visible: false, layout: { columns: 6 }, properties: { septemDataSourceId: 'source', septemVisRequester: 'no' } } };
  const number = changeNativeElementType(list, 'number');
  assert.equal(number.id, list.id); assert.equal(number.key, list.key); assert.equal(number.label, 'Valor');
  assert.equal(number.config.values, undefined); assert.equal(number.config.validate.required, true);
  assert.equal(number.config.visible, false); assert.equal(number.config.description, 'Ajuda');
  assert.equal(number.config.properties.septemDataSourceId, 'source');
  assert.deepEqual(number.config.layout, { columns: 6 });
  assert.ok(list.config.values, 'não altera origem');
  assert.deepEqual(changeNativeElementType(list, 'radio').config.values, list.config.values);
  const multiline = changeNativeElementType({ ...createNativeElement('textfield'), config: { defaultValue: 'Inicial', placeholder: 'Digite', width: 8, validate: { minLength: 2, maxLength: 100 } } }, 'textarea');
  assert.equal(multiline.config.defaultValue, 'Inicial'); assert.equal(multiline.config.width, 8); assert.equal(multiline.config.placeholder, 'Digite');
  assert.deepEqual(multiline.config.validate, { minLength: 2, maxLength: 100 });
  const upload = { ...createNativeElement('filepicker'), config: { properties: { septemDocGen: 'yes', septemDocGenConfig: '{}', septemAllowedExts: 'pdf', septemHelpText: 'Ajuda' } } };
  assert.deepEqual(changeNativeElementType(upload, 'textfield').config.properties, { septemHelpText: 'Ajuda' });
  const date = { ...createNativeElement('datetime'), config: { subtype: 'date', properties: { septemDateMode: 'date', septemDateLimit: 'noPast' } } };
  const text = changeNativeElementType(date, 'textfield');
  assert.equal(text.config.subtype, undefined); assert.equal(text.config.properties.septemDateMode, undefined);
  const renamed = editNativeElement(list, ['label'], 'Novo nome');
  assert.equal(renamed.id, list.id); assert.equal(renamed.key, list.key); assert.equal(renamed.label, 'Novo nome');
  assert.equal(editNativeElement(list, ['key'], 'changed').key, 'changed');
  assert.equal(editNativeElement(list, ['key'], 'changed').id, list.id);
  assert.throws(() => editNativeElement(list, ['__proto__', 'value'], 'unsafe'));
  assert.throws(() => changeNativeElementType(list, 'html'));
  const removed = editNativeElement(list, ['properties'], { septemDataSourceId: undefined });
  assert.deepEqual(removed.config.properties, {});
  assert.equal(list.config.properties.septemDataSourceId, 'source');
  for (const item of NATIVE_CATALOG) {
    const field = createNativeElement(item.type);
    const renamed = editNativeElement(field, ['label'], 'Renomeado');
    assert.equal(renamed.id, field.id);
    for (const target of NATIVE_CATALOG.filter(t => (t.category === 'Apresentação') === (item.category === 'Apresentação'))) {
      const changed = changeNativeElementType(field, target.type);
      assert.equal(changed.id, field.id); assert.equal(changed.key, field.key); assert.equal(changed.type, target.type);
    }
  }
  const first = createNativeTab('Inicial'), second = createNativeTab('Outra');
  const definition = { format: 'septem-native', schemaVersion: 1, id: crypto.randomUUID(), tabs: [first, second] };
  const table = createNativeTable('Itens', ['textfield', 'number']);
  first.groups.push(table);
  const photo = { ...createNativeElement('image'), config: { source: 'foto.png', description: 'Imagem preservada' } };
  first.groups[0].fields.push(list, photo);
  const published = structuredClone(definition);
  moveNativeElement(definition, first.groups[0].id, list.id, second.groups[0].id);
  assert.deepEqual(second.groups[0].fields[0], list);
  const beforeBlocked = structuredClone(definition);
  assert.throws(() => moveNativeElement(definition, second.groups[0].id, list.id, table.id), /Transferir/);
  assert.deepEqual(definition, beforeBlocked);
  moveNativeElement(definition, second.groups[0].id, list.id, table.id, undefined, true);
  assert.deepEqual(table.fields.at(-1), list);
  const column = table.fields[1];
  moveNativeElement(definition, table.id, column.id, table.id, table.fields[0].id);
  assert.equal(table.fields[0].id, column.id);
  const table2 = createNativeTable('Outros', ['checkbox']); first.groups.push(table2);
  assert.throws(() => moveNativeElement(definition, table.id, list.id, table2.id));
  moveNativeElement(definition, table.id, list.id, table2.id, undefined, true);
  assert.deepEqual(table2.fields.at(-1), list);
  assert.throws(() => moveNativeElement(definition, first.groups[0].id, photo.id, table.id, undefined, true), /apresentação/);
  assert.throws(() => convertNativeGroup(definition, first.groups[0].id), /Escolha/);
  assert.throws(() => convertNativeGroup(definition, first.groups[0].id, table.id), /Padrão/);
  const mixedField = createNativeElement('textfield');
  first.groups[0].fields.push(mixedField);
  convertNativeGroup(definition, first.groups[0].id, second.groups[0].id);
  assert.deepEqual(first.groups[0].fields, [mixedField], 'grupo misto preserva campo e realoca somente apresentação');
  assert.equal(first.groups[0].type, 'table'); assert.deepEqual(second.groups[0].fields[0], photo);
  const columns = structuredClone(table.fields);
  convertNativeGroup(definition, table.id);
  assert.equal(first.groups[1].type, 'group'); assert.deepEqual(first.groups[1].fields, columns);
  convertNativeGroup(definition, table.id);
  assert.equal(first.groups[1].type, 'table'); assert.deepEqual(first.groups[1].fields, columns);
  assert.equal(published.tabs[0].groups[0].type, 'group'); assert.deepEqual(published.tabs[0].groups[0].fields, [list, photo]);
  assert.throws(() => createNativeTable('Inválida', ['image'])); assert.throws(() => createNativeTable('Vazia', []));
  console.log('PASSOU: catálogo, identidade, compatibilidade, movimentação, cardinalidade e conversão com preservação de conteúdo.');
} finally { await rm(dir, { recursive: true, force: true }); }
